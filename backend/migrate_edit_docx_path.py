"""
Разовый скрипт: добавляет колонку case_document_edits.docx_file_path
(text, nullable). Раньше ручная правка текста документа хранилась ТОЛЬКО
как JSON-массив строк (paragraphs_json), а при генерации итогового файла
эти строки заново накладывались на СВЕЖЕ отрендеренный из шаблона .docx —
по индексу абзаца. Из-за шаблонов с условной логикой ({% if %}) число
абзацев при разных значениях полей могло отличаться, и правки по индексу
иногда попадали не в те абзацы — в скачанном файле получались пустые
страницы.

Теперь правка применяется сразу к своему собственному рендеру (тому же
файлу, из которого взят текст для правки) и сохраняется на диск — путь к
этому файлу и хранится в новой колонке docx_file_path. Она и есть
источник истины при генерации; paragraphs_json остаётся только для показа
текста при повторном открытии редактора.

Существующие (сохранённые до этого обновления) записи правок останутся
без docx_file_path — они не потеряются и не сломаются, для них при
генерации по-прежнему сработает старый (менее надёжный) путь применения
по индексу с проверкой числа абзацев. Как только юрист откроет такой
документ на редактирование и сохранит правки заново — запись перейдёт на
новый надёжный путь.

Идемпотентен: если колонка уже есть — ничего не делает.

Запускать один раз с сервера, из папки backend, с активированным venv.
"""
from sqlalchemy import text
from database import engine

with engine.begin() as conn:
    conn.execute(text("ALTER TABLE case_document_edits ADD COLUMN IF NOT EXISTS docx_file_path VARCHAR"))
    print("Колонка case_document_edits.docx_file_path на месте (создана или уже существовала).")

print("Готово.")
